"""
DeepEval RAG evaluation test suite for the SG Property Advisory AI Agent.

Runs each question from testset.json against the live /chat/inspect endpoint,
then evaluates the response using four standard RAG metrics.

Prerequisites:
  1. Backend running:  uvicorn server:app --port 8001  (from sg-property-agent/backend/)
  2. MCP server running on port 8002
  3. testset.json generated by generate_synthetic_testset.py
  4. OPENAI_API_KEY set (used by DeepEval's LLM judge)

Run:
    cd "c:\\GEEMETH\\N\\Property Advisory AI Agent"
    deepeval test run testing/evaluation/test_rag.py

Override backend URL:
    BACKEND_URL=http://localhost:8001 deepeval test run testing/evaluation/test_rag.py
"""

import csv
import csv
import os
import uuid
from pathlib import Path

import pytest
import requests
from deepeval import assert_test
from deepeval.metrics import (
    AnswerRelevancyMetric,
    ContextualPrecisionMetric,
    ContextualRecallMetric,
    FaithfulnessMetric,
)
from deepeval.test_case import LLMTestCase
from dotenv import load_dotenv

load_dotenv(Path(__file__).parent / ".env.eval", override=True)

# ── Config ────────────────────────────────────────────────────────────────────

BACKEND_URL  = os.getenv("BACKEND_URL", "http://localhost:8001")
TESTSET_FILE = Path(__file__).parent / "testset.csv"
TIMEOUT_S    = 120  # per-question API timeout

# ── Metrics (gpt-4o as judge) ─────────────────────────────────────────────────
# threshold=0.8 is the starting bar — raise to 0.9+ once baseline is established.

_METRICS = [
    FaithfulnessMetric(threshold=0.8),
    AnswerRelevancyMetric(threshold=0.8),
    ContextualPrecisionMetric(threshold=0.8),
    ContextualRecallMetric(threshold=0.8),
]

# ── Load test set ─────────────────────────────────────────────────────────────

def _load_testset() -> list[dict]:
    if not TESTSET_FILE.exists():
        pytest.skip(
            f"testset.csv not found at {TESTSET_FILE}. "
            "Run generate_synthetic_testset.py first."
        )
    records = []
    with TESTSET_FILE.open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            records.append({
                "Source": row.get("Source", ""),
                "input": row.get("Question", ""),
                "expected_output": row.get("Answer", ""),
                "context": [],
            })
    if not records:
        pytest.skip("testset.csv is empty.")
    return records


# ── Helper ─────────────────────────────────────────────────────────────────────

def _call_inspect(question: str) -> dict:
    """POST to /chat/inspect and return the JSON response."""
    payload = {"question": question, "thread_id": str(uuid.uuid4())}
    resp = requests.post(
        f"{BACKEND_URL}/chat/inspect",
        json=payload,
        timeout=TIMEOUT_S,
    )
    resp.raise_for_status()
    return resp.json()


def _extract_retrieval_context(chunks_by_agent: dict) -> list[str]:
    """Flatten all retrieved chunks from all agents into a single list of text strings."""
    texts = []
    for agent_chunks in chunks_by_agent.values():
        for chunk in agent_chunks:
            text = chunk.get("text", "").strip()
            if text:
                texts.append(text)
    return texts


# ── Parametrised test ─────────────────────────────────────────────────────────

def _make_test_cases() -> list[tuple[str, str, str, list[str]]]:
    """Return list of (test_id, question, expected_output, synthesis_context)."""
    records = _load_testset()
    cases = []
    for i, rec in enumerate(records):
        question        = rec.get("input", "")
        expected_output = rec.get("expected_output", "")
        # Context from the synthesizer (document chunks used to generate the question).
        # This is the "ground truth" context for ContextualRecall.
        synth_context = rec.get("context", [])
        if isinstance(synth_context, list):
            synth_context = [str(c) for c in synth_context]
        cases.append((f"TC-{i+1:03d}", question, expected_output, synth_context))
    return cases


_TEST_CASES = _make_test_cases()


@pytest.mark.parametrize("test_id,question,expected_output,synth_context", _TEST_CASES)
def test_rag_quality(
    test_id: str,
    question: str,
    expected_output: str,
    synth_context: list[str],
) -> None:
    """
    For each synthetic question:
      1. Call /chat/inspect to get the agent's answer + retrieved chunks
      2. Build an LLMTestCase with retrieval_context from the agent's actual chunks
      3. Assert all 4 RAG metrics pass
    """
    if not question.strip():
        pytest.skip(f"{test_id}: empty question, skipping.")

    print(f"\n{'─'*60}")
    print(f"[{test_id}] {question}")

    # Call the live agent
    result = _call_inspect(question)
    actual_output = result.get("answer", "")

    print(f"  Expected : {expected_output[:120]}{'…' if len(expected_output) > 120 else ''}")
    print(f"  Answer   : {actual_output[:120]}{'…' if len(actual_output) > 120 else ''}")

    # Retrieval context = what the agent actually retrieved (for Faithfulness + Precision)
    retrieval_context = _extract_retrieval_context(
        result.get("retrieved_chunks", {})
    )

    # Fall back to synthesizer context if agent returned nothing (e.g. chitchat intent)
    if not retrieval_context:
        retrieval_context = synth_context

    print(f"  Chunks   : {len(retrieval_context)} retrieved")
    for i, chunk in enumerate(retrieval_context[:3], 1):
        print(f"    [{i}] {chunk[:150]}{'…' if len(chunk) > 150 else ''}")
    if len(retrieval_context) > 3:
        print(f"    … and {len(retrieval_context) - 3} more")

    test_case = LLMTestCase(
        input=question,
        actual_output=actual_output,
        expected_output=expected_output,
        retrieval_context=retrieval_context,
    )

    # Measure each metric individually first so we can print reasons, then assert
    for metric in _METRICS:
        try:
            metric.measure(test_case)
            reason = getattr(metric, "reason", "") or ""
            icon   = "✓" if metric.is_successful() else "✗"
            print(f"  {metric.__class__.__name__:<30} {metric.score:.2f} {icon}")
            if reason:
                print(f"    → {reason[:200]}{'…' if len(reason) > 200 else ''}")
        except Exception:
            pass

    assert_test(test_case, _METRICS)
